// testCreds are the well-known AWS documentation credentials. The expected
// signatures below were produced by botocore's S3SigV4Auth for the exact same
// requests and timestamp, which is what makes them a real cross-check rather
// than a restatement of this package's own logic.
const (
	testAccessKey = "AKIAIOSFODNN7EXAMPLE"
	testSecretKey = "wJalrXUtnFEMI/K7MDENG/bPxRfiCYEXAMPLEKEY"
	testRegion    = "auto"
	// testTime is the fixed instant every vector was signed at.
	testInstant = "2026-10-14T09:01:25Z"
	// testDateStamp and testAmzDate are testInstant in the two SigV4 formats.
	testDateStamp = "20261014"
	testAmzDate   = "20261014T090125Z"
	// putPayloadHash is the SHA-256 of "Welcome to Amazon S3.".
	putPayloadHash = "44ce7dd67c959e0d3524ffac1771dfbba87d2b6b4b4e99e42034a8b803f8b072"
)

func testSigner() signer {
	return signer{accessKey: testAccessKey, secretKey: testSecretKey, region: testRegion}
}

func mustParseURL(t *testing.T, raw string) *url.URL {
	t.Helper()
	parsed, err := url.Parse(raw)
	if err != nil {
		t.Fatalf("parse %q: %v", raw, err)
	}
	return parsed
}

func mustTime(t *testing.T) time.Time {
	t.Helper()
	when, err := time.Parse(time.RFC3339, testInstant)
	if err != nil {
		t.Fatalf("parse time: %v", err)
	}
	return when
}

// TestSignMatchesBotocore pins the signature for four request shapes against
// values generated by botocore. If any of these fail the client cannot talk to
// a real bucket, so this is the single most important test in the package.
func TestSignMatchesBotocore(t *testing.T) {
	cases := []struct {
		name        string
		method      string
		rawURL      string
		contentType string
		payloadHash string
		wantAuth    string
	}{
		{
			name:        "get object",
			method:      http.MethodGet,
			rawURL:      "https://acct.r2.cloudflarestorage.com/bucket/test.txt",
			payloadHash: EmptySHA256,
			wantAuth: "AWS4-HMAC-SHA256 Credential=AKIAIOSFODNN7EXAMPLE/20261014/auto/s3/aws4_request, " +
				"SignedHeaders=host;x-amz-content-sha256;x-amz-date, " +
				"Signature=3452b538f9e4a4e6908473655abb12e2e37d6efc59cdffa86fa4fb87d1678bd4",
		},
		{
			name:        "put object with content type",
			method:      http.MethodPut,
			rawURL:      "https://acct.r2.cloudflarestorage.com/bucket/backups/p1/daily/2026-01-01.sqlite",
			contentType: "application/octet-stream",
			payloadHash: putPayloadHash,
			wantAuth: "AWS4-HMAC-SHA256 Credential=AKIAIOSFODNN7EXAMPLE/20261014/auto/s3/aws4_request, " +
				"SignedHeaders=content-type;host;x-amz-content-sha256;x-amz-date, " +
				"Signature=515b9b8b8fb94d03db130e0a04c18895d377258fb257ba7a42ed0f5fd60ecadd",
		},
		{
			name:        "list with prefix",
			method:      http.MethodGet,
			rawURL:      "https://acct.r2.cloudflarestorage.com/bucket?list-type=2&prefix=backups/p1/",
			payloadHash: EmptySHA256,
			wantAuth: "AWS4-HMAC-SHA256 Credential=AKIAIOSFODNN7EXAMPLE/20261014/auto/s3/aws4_request, " +
				"SignedHeaders=host;x-amz-content-sha256;x-amz-date, " +
				"Signature=d85a851e2722acac56c90d33f223b4d993f97fac6dc9de19a045f5f300f44921",
		},
		{
			name:        "delete object",
			method:      http.MethodDelete,
			rawURL:      "https://acct.r2.cloudflarestorage.com/bucket/backups/p1/latest.sqlite",
			payloadHash: EmptySHA256,
			wantAuth: "AWS4-HMAC-SHA256 Credential=AKIAIOSFODNN7EXAMPLE/20261014/auto/s3/aws4_request, " +
				"SignedHeaders=host;x-amz-content-sha256;x-amz-date, " +
				"Signature=ac861d12ecf105e128c07cd7d35f09d1a998bff4e4a919a3aae599dba6b47459",
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			req, err := http.NewRequest(tc.method, tc.rawURL, nil)
			if err != nil {
				t.Fatalf("new request: %v", err)
			}
			if tc.contentType != "" {
				req.Header.Set("Content-Type", tc.contentType)
			}

			testSigner().sign(req, tc.payloadHash, mustTime(t))

			if got := req.Header.Get("Authorization"); got != tc.wantAuth {
				t.Errorf("Authorization mismatch\n got: %s\nwant: %s", got, tc.wantAuth)
			}
		})
	}
}

// TestCanonicalRequestFormat asserts the exact bytes of the canonical request,
// including the two blank lines the spec requires. A single stray byte here
// breaks every signature, and it is invisible in the high-level test above.
func TestCanonicalRequestFormat(t *testing.T) {
	req, err := http.NewRequest(http.MethodGet, "https://acct.r2.cloudflarestorage.com/bucket/test.txt", nil)
	if err != nil {
		t.Fatalf("new request: %v", err)
	}
	req.Header.Set("X-Amz-Date", testAmzDate)
	req.Header.Set("X-Amz-Content-Sha256", EmptySHA256)

	signer := testSigner()
	canonical, signedHeaders := canonicalRequest(req, EmptySHA256, signer.signedHeaderValues(req))

	want := "GET\n" +
		"/bucket/test.txt\n" +
		"\n" +
		"host:acct.r2.cloudflarestorage.com\n" +
		"x-amz-content-sha256:" + EmptySHA256 + "\n" +
		"x-amz-date:" + testAmzDate + "\n" +
		"\n" +
		"host;x-amz-content-sha256;x-amz-date\n" +
		EmptySHA256

	if canonical != want {
		t.Errorf("canonical request mismatch\n got: %q\nwant: %q", canonical, want)
	}
	if signedHeaders != "host;x-amz-content-sha256;x-amz-date" {
		t.Errorf("signed headers: got %q", signedHeaders)
	}
}

// TestSigningKeyMatchesKnownVector checks the HMAC chain against the worked
// example in the AWS documentation: secret "wJalrXUtnFEMI/K7MDENG+bPxRfiCY
// EXAMPLEKEY", us-east-1, iam, 20120215. It pins the derivation independently
// of the request formatting.
func TestSigningKeyMatchesKnownVector(t *testing.T) {
	const (
		documentedSecret = "wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY"
		wantKey          = "f4780e2d9f65fa895f9c67b32ce1baf0b0d8a43505a000a1a9e090d414db404d"
	)

	got := hex.EncodeToString(deriveSigningKey(documentedSecret, "20120215", "us-east-1", "iam"))
	if got != wantKey {
		t.Errorf("deriveSigningKey = %s, want %s", got, wantKey)
	}
}

// TestAwsURIEncode covers the encoding table, including the characters that
// differ from net/url's helpers ('/' and '~').
func TestAwsURIEncode(t *testing.T) {
	cases := []struct {
		in          string
		encodeSlash bool
		want        string
	}{
		{"abcXYZ019-_.~", true, "abcXYZ019-_.~"},
		{"a/b", true, "a%2Fb"},
		{"a/b", false, "a/b"},
		{"backups/p1/daily/2026-01-01.sqlite", true, "backups%2Fp1%2Fdaily%2F2026-01-01.sqlite"},
		{"a b", true, "a%20b"},
		{"a+b", true, "a%2Bb"},
		{"100%", true, "100%25"},
	}
	for _, tc := range cases {
		if got := awsURIEncode(tc.in, tc.encodeSlash); got != tc.want {
			t.Errorf("awsURIEncode(%q, %v) = %q, want %q", tc.in, tc.encodeSlash, got, tc.want)
		}
	}
}

